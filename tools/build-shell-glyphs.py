"""The taskbar clock's glyphs as the approved prototype's own pixels, for src/pw_text_glyphs.h (Wine patch 1140).

themes/windows11/taskbar/clock-{light,dark}.json hold every character an en-US clock shows, in the font and colour of the
prototype's .tb-date, alone at the four quarter-pixel pen phases, over black and over white, and eight clock strings as
Chromium laid them out (tools/measure-prototype-glyphs.mjs, from prototypes/windows11-shell at 1920 x 1080):

  node tools/measure-prototype-glyphs.mjs <out> <theme> .tb-date '0123456789/:. -APM' 10/16/2026 '2:18 PM' \
       '12:59 AM' 1/1/2027 '10:07 AM' 12/31/2026 '11:48 PM' 9/9/2029

Each glyph is premultiplied BGRA as tools/build-shell-sprites.py makes a sprite. Written to
.deps/windows11-theme/pw_shell_glyphs.h (the fonts) and pw_shell_glyph_checks.h (the strings with their captured
premultiplied pixels, for tests/test_pw_text_glyphs.c).
"""
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'themes/windows11/taskbar'
OUTPUT = ROOT / '.deps/windows11-theme'
THEMES = ('light', 'dark')
_sprites = importlib.util.spec_from_file_location('build_shell_sprites', ROOT / 'tools/build-shell-sprites.py')
sprites = importlib.util.module_from_spec(_sprites)
_sprites.loader.exec_module(sprites)


def words(values):
    return ',\n'.join(','.join(f'0x{w:08x}' for w in values[i:i + 12]) for i in range(0, len(values), 12))


def write(path, lines):
    text = '\n'.join(lines + [''])
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def main():
    fonts = {theme: json.loads((SOURCE / f'clock-{theme}.json').read_text()) for theme in THEMES}
    if any(set(fonts[t]['glyphs']) != set(fonts['light']['glyphs']) for t in THEMES):
        raise ValueError('the themes measured different characters')
    glyphs = ['/* Generated by tools/build-shell-glyphs.py from themes/windows11/taskbar/clock-*.json: do not edit. */',
              '#ifndef PW_SHELL_GLYPHS_H', '#define PW_SHELL_GLYPHS_H', '#include "pw_text_glyphs.h"']
    checks = ['/* Generated by tools/build-shell-glyphs.py from themes/windows11/taskbar/clock-*.json: do not edit. */',
              '#ifndef PW_SHELL_GLYPH_CHECKS_H', '#define PW_SHELL_GLYPH_CHECKS_H',
              'struct pw_glyph_check { const char *text; int x, baseline, x0, y0, w, h; const unsigned int *bgra; };']
    for theme in THEMES:
        font = fonts[theme]
        entries = []
        for index, (ch, glyph) in enumerate(sorted(font['glyphs'].items())):
            if glyph['advance'] * 65536 != round(glyph['advance'] * 65536):
                raise ValueError(f'{theme} {ch!r}: advance {glyph["advance"]} is not a 16.16 value')
            phases = []
            for phase, image in enumerate(glyph['phases']):
                name = f'pw_glyph_{theme}_{index}_{phase}'
                pixels = sprites.premultiplied(image) if image['w'] else [0]
                glyphs.append(f'static const unsigned int {name}[] = {{\n{words(pixels)}}};')
                phases.append(f'{{{image["x"]}, {image["y"]}, {image["w"]}, {image["h"]}, {name}, 0}}')
            entries.append(f'    {{0x{ord(ch):04x}, {round(glyph["advance"] * 65536)}, {{{", ".join(phases)}}}}},')
        glyphs += [f'static const PwGlyph pw_shell_clock_glyphs_{theme}[] = {{'] + entries + ['};']
        rows = []
        for index, string in enumerate(font['strings']):
            name = f'pw_glyph_check_{theme}_{index}'
            checks.append(f'static const unsigned int {name}[] = {{\n{words(sprites.premultiplied(string))}}};')
            rows.append(f'    {{{json.dumps(string["text"])}, {round(string["x"] * 65536)}, {string["baseline"]}, '
                        f'{string["x0"]}, {string["y0"]}, {string["w"]}, {string["h"]}, {name}}},')
        checks += [f'static const struct pw_glyph_check pw_glyph_checks_{theme}[] = {{'] + rows + ['};']
    glyphs.append('/* [0] light, [1] dark: the clock\'s font and TextFillColorPrimary in each theme. */')
    glyphs.append('static const PwGlyphFont pw_shell_clock_glyphs[2] = {')
    for theme in THEMES:
        font = fonts[theme]['font']
        glyphs.append(f'    {{pw_shell_clock_glyphs_{theme}, {len(fonts[theme]["glyphs"])}, {font["baseline"]}, '
                      f'{round(font["line"])}, 0}},')
    glyphs += ['};', '#endif']
    checks += ['#endif']
    write(OUTPUT / 'pw_shell_glyphs.h', glyphs)
    write(OUTPUT / 'pw_shell_glyph_checks.h', checks)
    print(json.dumps({'glyphs': len(fonts['light']['glyphs']), 'themes': len(THEMES),
                      'header': str((OUTPUT / 'pw_shell_glyphs.h').relative_to(ROOT))}))


if __name__ == '__main__':
    main()

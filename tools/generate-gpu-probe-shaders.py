"""Regenerate the synthetic broker probe's SPIR-V with a pinned local compiler."""
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile
ROOT=Path(__file__).resolve().parents[1]
COMPILER=Path('/usr/bin/glslangValidator')
PIN='16979fe805c7e1f067c7470763bba4a98a58bb227b448a1d35dc69b1b373b6a9'
if hashlib.sha256(COMPILER.read_bytes()).hexdigest()!=PIN:
    raise SystemExit('Shader compiler differs from pinned glslang 16.4.0; generated header preserved')
lines=['/* SPDX-License-Identifier: GPL-3.0-or-later */', '/* Generated by tools/generate-gpu-probe-shaders.py; glslang sha256 '+PIN+' */', '#include <stdint.h>']
with tempfile.TemporaryDirectory(prefix='proton-gpu-shaders-') as work:
    for stage in ('vert','frag'):
        source=ROOT/'native/shaders'/('gpu-probe.'+stage);output=Path(work)/(stage+'.spv')
        subprocess.run([str(COMPILER),'-V','--target-env','vulkan1.1','-o',str(output),str(source)],check=True)
        data=output.read_bytes();words=struct.unpack('<'+'I'*(len(data)//4),data)
        lines+=['/* source sha256 '+hashlib.sha256(source.read_bytes()).hexdigest()+' */','static const uint32_t gpu_probe_'+stage+'[] = {']
        lines+=['    '+','.join('0x%08xu'%w for w in words[i:i+8])+',' for i in range(0,len(words),8)]
        lines+=['};']
(ROOT/'native/proton_gpu_probe_spv.h').write_text('\n'.join(lines)+'\n')

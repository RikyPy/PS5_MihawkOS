"""File Explorer's fixed chrome as the approved prototype's own pixels, for the native File Explorer (Wine patch 1150).

themes/windows11/explorer/explorer-{light,dark}.json.gz hold every element tools/measure-explorer-sprites.mjs captured
alone over black and over white, in the state it shows (a location, a selection, the pointer over it), over the box
that covers its sub-pixel position. Each becomes premultiplied 32-bit BGRA, as GdiAlphaBlend takes it (the same
recovery as tools/build-shell-sprites.py), run-length coded on its transparent pixels (most of a sprite is clear), in
.deps/windows11-theme/pw_explorer_sprites.h: per sprite its size, the captured region's top left in client
coordinates of the prototype's 1100 x 700 window (x, y) and that region's offset from its element's box rounded down
(dx, dy), so a sprite is drawn at the element's box, wherever the layout (src/pw_explorer_layout.h) puts it.

The code is a word stream: (clear << 16 | literal) then `literal` BGRA words, until width x height pixels are done.
"""
import gzip
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
SOURCE = ROOT / 'themes/windows11/explorer'
OUTPUT = ROOT / '.deps/windows11-theme/pw_explorer_sprites.h'


def premultiplied(sprite):
    from importlib import import_module
    return import_module('build-shell-sprites').premultiplied(sprite)


def runs(words):
    """The transparent-run code of one sprite's pixels."""
    out, i = [], 0
    while i < len(words):
        clear = 0
        while i < len(words) and not words[i] and clear < 0xffff: clear += 1; i += 1
        start = i
        while i < len(words) and words[i] and i - start < 0xffff: i += 1
        out.append(clear << 16 | (i - start)); out += words[start:i]
    return out


def main():
    themes = [json.loads(gzip.decompress((SOURCE / f'explorer-{theme}.json.gz').read_bytes()))['sprites'] for theme in ('light', 'dark')]
    names = list(themes[0])
    if list(themes[1]) != names:
        raise ValueError(f'the themes measured different sprites: {sorted(set(names) ^ set(themes[1]))}')
    symbol = lambda name: name.upper().replace('-', '_')
    lines = ['/* Generated by tools/build-explorer-sprites.py from themes/windows11/explorer: do not edit. */',
             '#ifndef PW_EXPLORER_SPRITES_H', '#define PW_EXPLORER_SPRITES_H',
             'struct pw_explorer_sprite { short width, height, x, y, dx, dy; const unsigned int *code; };',
             'enum {' + ', '.join(f'PW_XS_{symbol(n)}' for n in names) + ', PW_XS_COUNT};']
    total = 0
    for theme, sprites in zip(('light', 'dark'), themes):
        for name in names:
            s = sprites[name]
            if (s['w'], s['h']) != (themes[0][name]['w'], themes[0][name]['h']):
                raise ValueError(f'{name}: {theme} is {s["w"]}x{s["h"]}, light {themes[0][name]["w"]}x{themes[0][name]["h"]}')
            code = runs(premultiplied(s))
            total += len(code) * 4
            body = ',\n'.join(','.join(f'0x{w:08x}' for w in code[i:i + 12]) for i in range(0, len(code), 12))
            lines.append(f'static const unsigned int pw_xs_{theme}_{name.replace("-", "_")}[] = {{\n{body}}};')
    lines.append('static const struct pw_explorer_sprite pw_explorer_sprites[2][PW_XS_COUNT] = {')
    for theme, sprites in zip(('light', 'dark'), themes):
        entries = []
        for name in names:
            s = sprites[name]
            dx, dy = s['x'] - math.floor(s['box'][0] + 1e-6), s['y'] - math.floor(s['box'][1] + 1e-6)
            entries.append(f'{{{s["w"]}, {s["h"]}, {s["x"]}, {s["y"]}, {dx}, {dy}, pw_xs_{theme}_{name.replace("-", "_")}}}')
        lines.append('    {' + ',\n     '.join(entries) + '},')
    lines += ['};', '#endif', '']
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    text = '\n'.join(lines)
    if not OUTPUT.exists() or OUTPUT.read_text() != text:
        OUTPUT.write_text(text)
    print(json.dumps({'sprites': len(names), 'themes': 2, 'bytes': total, 'header': str(OUTPUT.relative_to(ROOT))}))


if __name__ == '__main__':
    main()

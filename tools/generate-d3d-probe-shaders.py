"""Compile our synthetic HLSL with the existing pinned host Wine; no fetches."""
import hashlib
import os
from pathlib import Path
import subprocess
import tempfile

ROOT=Path(__file__).resolve().parents[1]
WINE=ROOT/'.deps/wine-runtime'
PIN='a518d643873ff733bafb31595dfd01ab8bbdf790'
if (WINE/'revision').read_text().strip()!=PIN:
    raise SystemExit('Host Wine revision differs; shader header preserved')
compiler=WINE/'build/dlls/d3dcompiler_47/x86_64-windows/d3dcompiler_47.dll'
COMPILER_PIN='ad482c7c093adaaf7c5eb9bf187f424dff669292f23f9adc4c8eff3bebeaacd5'
if hashlib.sha256(compiler.read_bytes()).hexdigest()!=COMPILER_PIN:
    raise SystemExit('Host HLSL compiler differs; shader header preserved')
source=ROOT/'tests/shaders/d3d11-triangle.hlsl'
program=r'''
#define COBJMACROS
#include <windows.h>
#include <d3dcompiler.h>
void mainCRTStartup(void) {
    char input[4096]; DWORD size, written; ID3DBlob *code;
    HANDLE f=CreateFileA("triangle.hlsl",GENERIC_READ,0,NULL,OPEN_EXISTING,0,NULL);
    if(f==INVALID_HANDLE_VALUE || !ReadFile(f,input,sizeof(input),&size,NULL))ExitProcess(1);
    CloseHandle(f);
    const char *entries[]={"vs","ps"}, *profiles[]={"vs_5_0","ps_5_0"}, *paths[]={"vs.dxbc","ps.dxbc"};
    for(unsigned i=0;i<2;++i) {
        if(FAILED(D3DCompile(input,size,NULL,NULL,NULL,entries[i],profiles[i],0,0,&code,NULL)))ExitProcess(2);
        f=CreateFileA(paths[i],GENERIC_WRITE,0,NULL,CREATE_ALWAYS,0,NULL);
        if(f==INVALID_HANDLE_VALUE || !WriteFile(f,ID3D10Blob_GetBufferPointer(code),ID3D10Blob_GetBufferSize(code),&written,NULL) || written!=ID3D10Blob_GetBufferSize(code))ExitProcess(3);
        CloseHandle(f);ID3D10Blob_Release(code);
    }
    ExitProcess(0);
}
'''
prefix=ROOT/'.deps/process-host-prefix'
if not (prefix/'drive_c').is_dir():
    raise SystemExit('Initialize the dedicated host probe prefix first')
with tempfile.TemporaryDirectory(prefix='proton-dxbc-') as temporary:
    work=Path(temporary);(work/'compile.c').write_text(program);(work/'triangle.hlsl').write_bytes(source.read_bytes())
    subprocess.run(['clang','--target=x86_64-windows','--no-default-config','-fuse-ld=lld','-nostdlib','-O2',
        '-I'+str(WINE/'source/include'),'-I'+str(WINE/'build/include'),'-I'+str(WINE/'source/include/msvcrt'),
        '-Wl,/entry:mainCRTStartup','-Wl,/subsystem:console',str(work/'compile.c'),
        str(WINE/'build/dlls/kernel32/x86_64-windows/libkernel32.a'),
        str(WINE/'build/dlls/d3dcompiler_47/x86_64-windows/libd3dcompiler.a'),'-o',str(work/'compile.exe')],check=True)
    env=dict(os.environ,WINEPREFIX=str(prefix),WINEDEBUG='-all',WINEDLLOVERRIDES='winemenubuilder.exe=d;d3dcompiler_47=b')
    subprocess.run([str(WINE/'build/loader/wine'),str(work/'compile.exe')],cwd=work,env=env,check=True,timeout=60)
    lines=['/* SPDX-License-Identifier: GPL-3.0-or-later */',
        '/* Generated by tools/generate-d3d-probe-shaders.py; Wine '+PIN+' */',
        '/* Compiler sha256 '+COMPILER_PIN+' */',
        '/* HLSL sha256 '+hashlib.sha256(source.read_bytes()).hexdigest()+' */']
    for stage in ('vs','ps'):
        data=(work/(stage+'.dxbc')).read_bytes()
        if data[:4]!=b'DXBC':raise RuntimeError('Compiler output is not DXBC')
        lines+=['/* DXBC sha256 '+hashlib.sha256(data).hexdigest()+' */',
                'static const unsigned char d3d_probe_'+stage+'[] = {']
        lines+=['    '+','.join('0x%02x'%b for b in data[i:i+16])+',' for i in range(0,len(data),16)]
        lines+=['};']
    (ROOT/'tests/shaders/d3d11-triangle.h').write_text('\n'.join(lines)+'\n')

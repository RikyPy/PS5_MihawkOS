"""Tooltips' text as the approved prototype's own glyphs, for src/pw_tooltip.h (comctl32, Wine patch 1210).

themes/windows11/tooltip holds what tools/measure-prototype-glyphs.mjs and tools/measure-prototype-sprites.mjs captured
from prototypes/windows11-shell at 1920 x 1080, each over black and over white, gzipped:

  glyphs-{light,dark}.json.gz  every printable ASCII character in the .tooltip's font and colour (TextFillColorPrimary:
      black at 89.4%, white in dark): PROTOTYPE_SETUP="Shell.tooltip.show(document.querySelector('.desk'), 'x');
      Shell.tooltip.hide()", then measure-prototype-glyphs.mjs <out> <theme> '.tooltip' <chars>
  texts-{light,dark}.json.gz  three tooltips as Chromium drew them, their text alone: PROTOTYPE_SETUP adds
      '.tooltip{background:none;border-color:transparent;box-shadow:none;backdrop-filter:none}' (all !important; the
      light acrylic's backdrop filter turns the black ground grey otherwise) and shows each of TEXTS with
      Shell.tooltip.show(desk, text, {rect: {left: 40, right: 40, top: 100, bottom: 100}, placement: 'bottom'}); then
      measure-prototype-sprites.mjs <out> - <theme> 'tip=.tooltip', merged as tip-0..2

Each layer is one colour, so its glyphs are kept as alpha (src/pw_text_glyphs.h), which this checks. Written to
.deps/windows11-theme/pw_tooltip_glyphs.h, and the captured tooltips to pw_tooltip_glyph_checks.h for tests/test_pw_tooltip.c.
"""
import gzip
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'themes/windows11/tooltip'
OUTPUT = ROOT / '.deps/windows11-theme'
THEMES = {'light': 0xff000000, 'dark': 0xffffffff}   # the opaque colour each theme's alpha glyphs take
TEXTS = ['Contains the files and folders that you have deleted.',
         'Type: Text Document\nSize: 2.1 KB\nDate modified: 10/9/2026 7:22 PM',
         'A long tooltip that wraps: Program Files (x86) and Supercalifragilisticexpialidocious words in a line of text '
         'that is wider than 320 pixels']
_desktop = importlib.util.spec_from_file_location('build_desktop_sprites', ROOT / 'tools/build-desktop-sprites.py')
desktop = importlib.util.module_from_spec(_desktop)
_desktop.loader.exec_module(desktop)


def load(name):
    return json.loads(gzip.decompress((SOURCE / f'{name}.json.gz').read_bytes()))


def main():
    out = ['/* Generated by tools/build-tooltip-glyphs.py from themes/windows11/tooltip: do not edit. */',
           '#ifndef PW_TOOLTIP_GLYPHS_H', '#define PW_TOOLTIP_GLYPHS_H', '#include "pw_text_glyphs.h"']
    checks = ['/* Generated by tools/build-tooltip-glyphs.py from themes/windows11/tooltip: do not edit. */',
              '#ifndef PW_TOOLTIP_GLYPH_CHECKS_H', '#define PW_TOOLTIP_GLYPH_CHECKS_H',
              '/* A tooltip\'s text as Chromium drew it (premultiplied BGRA, the box with its background off) in a theme. */',
              'struct pw_tooltip_check { const char *text; int dark, w, h; const unsigned int *bgra; };']
    fonts, rows = {}, []
    for number, (theme, colour) in enumerate(THEMES.items()):
        font = load(f'glyphs-{theme}')
        entries = []
        for index, (ch, glyph) in enumerate(sorted(font['glyphs'].items())):
            if glyph['advance'] * 65536 != round(glyph['advance'] * 65536):
                raise ValueError(f'{theme} {ch!r}: advance {glyph["advance"]} is not a 16.16 value')
            phases = []
            for phase, image in enumerate(glyph['phases']):
                if not image['w']:
                    phases.append('{0, 0, 0, 0, 0, 0}')
                    continue
                pixels = desktop.premultiplied(image)
                if any(abs(c - (alpha * (colour & 0xff) + 127) // 255) > 1 for alpha, *rgb in pixels for c in rgb):
                    raise ValueError(f'{theme} {ch!r}: not one colour')
                name = f'pw_tooltip_glyph_{number}_{index}_{phase}'
                out.append(f'static const unsigned char {name}[] = {{{",".join(str(p[0]) for p in pixels)}}};')
                phases.append(f'{{{image["x"]}, {image["y"]}, {image["w"]}, {image["h"]}, 0, {name}}}')
            entries.append(f'    {{0x{ord(ch):04x}, {round(glyph["advance"] * 65536)}, {{{", ".join(phases)}}}}},')
        out += [f'static const PwGlyph pw_tooltip_glyphs_{number}[] = {{'] + entries + ['};']
        fonts[theme] = font
        for i, text in enumerate(TEXTS):
            sprite = load(f'texts-{theme}')['sprites'][f'tip-{i}']
            name = f'pw_tooltip_check_{number}_{i}'
            checks.append(f'static const unsigned int {name}[] = {{\n'
                          f'{desktop.words([desktop.word(p) for p in desktop.premultiplied(sprite)])}}};')
            rows.append(f'    {{{json.dumps(text)}, {number}, {sprite["w"]}, {sprite["h"]}, {name}}},')
    out.append('/* [0] light, [1] dark: TextFillColorPrimary at 12 px. */')
    out.append('static const PwGlyphFont pw_tooltip_fonts[2] = {')
    for number, (theme, colour) in enumerate(THEMES.items()):
        font = fonts[theme]['font']
        out.append(f'    {{pw_tooltip_glyphs_{number}, {len(fonts[theme]["glyphs"])}, {font["baseline"]}, {round(font["line"])}, '
                   f'0x{colour:08x}u}},')
    out += ['};', '#endif']
    checks += ['static const struct pw_tooltip_check pw_tooltip_checks[] = {'] + rows + ['};', '#endif']
    desktop.write(OUTPUT / 'pw_tooltip_glyphs.h', out)
    desktop.write(OUTPUT / 'pw_tooltip_glyph_checks.h', checks)
    print(json.dumps({'glyphs': len(fonts['light']['glyphs']), 'themes': len(THEMES), 'checks': len(rows),
                      'header': str((OUTPUT / 'pw_tooltip_glyphs.h').relative_to(ROOT))}))


if __name__ == '__main__':
    main()

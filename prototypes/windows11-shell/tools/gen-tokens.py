#!/usr/bin/env python3
"""Generate css/tokens.css from the repository's Windows 11 reference data.

Inputs (all in the repository): docs/windows11-reference/winui-colors.json (WinUI colour
resources, MIT, light and dark), docs/windows11-reference/tier-a.json (radii, motion, type
ramp), themes/windows11/appearance.json (shell metrics). Run from anywhere; idempotent.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
colors = json.loads((ROOT / "docs/windows11-reference/winui-colors.json").read_text())
tier_a = json.loads((ROOT / "docs/windows11-reference/tier-a.json").read_text())
appearance = json.loads((ROOT / "themes/windows11/appearance.json").read_text())


def css_color(argb: str) -> str:
    """WinUI writes #AARRGGBB or #RRGGBB; CSS wants rgba()."""
    h = argb.lstrip("#")
    if len(h) == 6:
        return "#" + h.lower()
    a, r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4, 6))
    return f"rgba({r}, {g}, {b}, {round(a / 255, 3)})"


def block(theme: str) -> str:
    return "\n".join(f"  --{k}: {css_color(v)};" for k, v in colors["themes"][theme].items())


m = appearance["metrics"]
motion = tier_a["motion"]
dur = motion["durations_ms"]
ein = motion["easing"]["fast_out_slow_in"]["cubic_bezier"]
eout = motion["easing"]["slow_out_fast_in"]["cubic_bezier"]

# Windows 11's default accent ramp (the "Blue" accent the system ships with); Settings
# recomputes the ramp at runtime when the user picks another accent (js/core.js).
